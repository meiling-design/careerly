/// 帮助中心的静态内容。
///
/// ## 为什么内容写在代码里而不是 Markdown 资产
///
/// 本页的交互是**分类 + 手风琴**，不是一整篇可连续滚动的文档；
/// 问题与答案需要各自成为可点击、可展开的节点。写成 Markdown 再解析，
/// 反而要维护一套「标题层级 → 分类」的约定。
///
/// ## 内容边界
///
/// 每条答案都对应**当前 App 真实可用的功能**。明确不写：
/// - 尚未实现的「编辑简历」「在 App 内直接编辑职业资产」；
/// - 尚未接入的推送通知；
/// - 任何后端不存在的「一键执行 AI 建议」。
///
/// 功能变化时**改这里**，页面与路由不需要动。
class HelpItem {
  const HelpItem({required this.question, required this.answer});

  final String question;
  final String answer;
}

/// 一个 FAQ 分类。
class HelpCategory {
  const HelpCategory({required this.title, required this.items});

  final String title;
  final List<HelpItem> items;
}

